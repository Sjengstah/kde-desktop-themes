#!/usr/bin/env python3
"""See-through window titlebars that look the same in KDE, GTK 3 and GTK 4 apps.

Usage:
  glass-deco.py svg <decoration.svg> [opacity]   make an Aurorae decoration translucent (default 0.35)
  glass-deco.py gtk <aurorae theme dir> <THEME>  write the matching GTK 3 / GTK 4 titlebar CSS
  glass-deco.py clear                            remove every theme's GTK titlebar CSS

svg: every theme's decoration.svg draws each piece as a shadow plus stacked solid layers.
Fading the layers one by one makes them stack back up to almost solid, so the solid layers
of each piece go into one group that gets the opacity. Running it again only changes the value.

gtk: reads the titlebar colour, opacity and title colours from the installed Aurorae theme,
so GTK headerbars always follow the window frame. The window buttons come from the images
KDE's GTK integration (kde-gtk-config) renders from the active KWin decoration.
Blocks are marked /* <THEME>-DECO-BEGIN */ … /* <THEME>-DECO-END */ in gtk-3.0/gtk.css
and gtk-4.0/gtk.css; only one theme's block is kept.

When it runs: "gtk" is called by desktop-theme when you switch themes, "clear" by
uninstall.sh. "svg" is a tool for building a theme's decoration, run by hand.
What it changes: "svg" edits the given decoration.svg in place; "gtk" and "clear" only
edit the marked block in ~/.config/gtk-3.0/gtk.css and ~/.config/gtk-4.0/gtk.css (your
own CSS outside that block is kept). Current user only, no sudo.
Undo: glass-deco.py clear
"""
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG = "{http://www.w3.org/2000/svg}"
CONF = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
DECO = re.compile(r"\n*/\* [A-Z]+-DECO-BEGIN \*/.*?/\* [A-Z]+-DECO-END \*/\n?", re.S)
SOLID = re.compile(r"fill:#[0-9a-f]{6}", re.I)


def is_solid(el):
    """A flat-colour body layer (the shadows use gradients, the masks have no fill)."""
    return el.tag == SVG + "path" and SOLID.search(el.get("style") or "")


def make_svg(path, opacity):
    src = path.read_text()
    if 'id="glass-' in src:   # already translucent: only set the value
        src = re.sub(r'style="opacity:[0-9.]+" id="glass-', f'style="opacity:{opacity}" id="glass-', src)
        for centre in re.findall(r'<path\b[^>]*\bid="decoration-(?:inactive-)?center"[^>]*>', src, re.S):
            src = src.replace(centre, re.sub(r"fill-opacity:[0-9.]+", f"fill-opacity:{opacity}", centre))
        path.write_text(src)
        return
    for prefix, uri in re.findall(r'xmlns:(\w+)="([^"]+)"', src):
        ET.register_namespace(prefix, uri)
    ET.register_namespace("", SVG[1:-1])
    root = ET.fromstring(src)
    seen, n = set(), 0
    for piece in [e for e in root.iter() if (e.get("id") or "").startswith("decoration-")]:
        if piece.tag == SVG + "path":   # the centre is one path: nothing stacks under it
            piece.set("style", re.sub(r"fill-opacity:[0-9.]+", f"fill-opacity:{opacity}", piece.get("style")))
            continue
        for parent in list(piece.iter()):
            if id(parent) in seen or (parent.get("id") or "").startswith("glass-"):
                continue
            seen.add(id(parent))
            kids = list(parent)
            idx = [i for i, c in enumerate(kids) if is_solid(c)]
            if not idx:
                continue
            group = ET.Element(SVG + "g", {"style": f"opacity:{opacity}", "id": f"glass-{n}"})
            n += 1
            for i in idx:
                parent.remove(kids[i])
                group.append(kids[i])
            parent.insert(idx[0], group)
    ET.ElementTree(root).write(path, xml_declaration=True, encoding="UTF-8")


def read_theme(theme_dir):
    """Titlebar colour + opacity from decoration.svg, title colours from the <name>rc."""
    svg = (theme_dir / "decoration.svg").read_text()
    centre = re.search(r'<path\b[^>]*\bid="decoration-center"[^>]*>', svg, re.S).group(0)
    fill = re.search(r"fill:#([0-9a-f]{6})", centre, re.I).group(1)
    alpha = float(re.search(r"fill-opacity:([0-9.]+)", centre).group(1))
    rgb = tuple(int(fill[i:i + 2], 16) for i in (0, 2, 4))
    rc = next(theme_dir.glob("*rc")).read_text()
    colour = lambda key: tuple(int(v) for v in re.search(rf"^{key}=([\d,]+)", rc, re.M).group(1).split(",")[:3])
    return rgb, alpha, colour("ActiveTextColor"), colour("InactiveTextColor")


def css_blocks(name, theme_dir):
    rgb, alpha, active, inactive = read_theme(theme_dir)
    bar = "rgba({}, {}, {}, {})".format(*rgb, alpha)
    act, ina = "rgb({}, {}, {})".format(*active), "rgb({}, {}, {})".format(*inactive)
    head = f"/* {name}-DECO-BEGIN */\n/* {name} titlebars, generated by glass-deco.py from the KWin decoration. */\n"
    tail = f"/* {name}-DECO-END */\n"

    gtk3 = head + f"""headerbar.titlebar, .titlebar:not(headerbar), window.csd > .titlebar,
headerbar.titlebar:backdrop, .titlebar:not(headerbar):backdrop, window.csd > .titlebar:backdrop {{
  background-color: {bar}; background-image: none; box-shadow: none;
}}
headerbar.titlebar .title {{ color: {act}; }}
headerbar.titlebar:backdrop .title {{ color: {ina}; }}
""" + tail

    # GTK 4 paints the window background under the headerbar, so leave its top clear.
    gtk4 = head + f"""window.csd.background:not(.dialog):not(.messagedialog) {{
  background-color: transparent;
  background-image: linear-gradient(to bottom, transparent 47px, var(--window-bg-color, @window_bg_color) 47px);
}}
headerbar, headerbar:backdrop {{
  background-color: {bar}; background-image: none; box-shadow: none; min-height: 47px;
}}
headerbar .title, windowtitle .title {{ color: {act}; }}
headerbar:backdrop .title, windowtitle:backdrop .title {{ color: {ina}; }}
windowcontrols > button, windowcontrols > button:hover, windowcontrols > button:active {{
  background-color: transparent; box-shadow: none; border-radius: 0; padding: 0; margin: 0 3px;
  min-width: 18px; min-height: 18px;
  background-repeat: no-repeat; background-position: center; background-size: contain;
}}
windowcontrols > button > image {{ opacity: 0; }}
"""
    states = [("", "normal"), (":hover", "hover"), (":active", "active"),
              (":backdrop", "backdrop-normal"), (":backdrop:hover", "backdrop-hover"),
              (":backdrop:active", "backdrop-active")]
    for button in ("close", "minimize", "maximize"):
        for state, img in states:
            gtk4 += f'windowcontrols > button.{button}{state} {{ background-image: url("../gtk-3.0/assets/{button}-{img}.svg"); }}\n'
    for state, img in states:
        gtk4 += f'window.maximized windowcontrols > button.maximize{state} {{ background-image: url("../gtk-3.0/assets/maximized-{img}.svg"); }}\n'
    return gtk3, gtk4 + tail


def write_block(css, block):
    text = css.read_text() if css.exists() else ""
    text = DECO.sub("\n", text).rstrip("\n")
    if block:
        text += ("\n\n" if text else "") + block
    css.parent.mkdir(parents=True, exist_ok=True)
    css.write_text(text + ("\n" if text and not text.endswith("\n") else ""))


def main(args):
    if args[:1] == ["svg"] and len(args) in (2, 3):
        make_svg(Path(args[1]), float(args[2]) if len(args) == 3 else 0.35)
    elif args[:1] == ["gtk"] and len(args) == 3:
        gtk3, gtk4 = css_blocks(args[2].upper(), Path(args[1]))
        write_block(CONF / "gtk-3.0/gtk.css", gtk3)
        write_block(CONF / "gtk-4.0/gtk.css", gtk4)
    elif args == ["clear"]:
        write_block(CONF / "gtk-3.0/gtk.css", "")
        write_block(CONF / "gtk-4.0/gtk.css", "")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
